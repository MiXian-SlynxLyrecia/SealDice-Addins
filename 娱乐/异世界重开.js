// 从数组中随机选择
const getRandomFromArray = (array) => {
  return array[Math.floor(Math.random() * array.length)];
};

// 随机开场文案选择函数
const getRandomStartText = (playerName) => {
    const randomText = RANDOM_START_TEXTS[Math.floor(Math.random() * RANDOM_START_TEXTS.length)];
    return randomText.replace('{player}', playerName);
};

// 计算人生评分并返回对应总结
const calculateLifeSummary = (events) => {
  let goodCount = 0;
  let badCount = 0;
  
  // 统计好坏事件数量
  Object.values(events).forEach(event => {
    if (event.isGood) goodCount++;
    else badCount++;
  });
  
  const ratio = goodCount / (goodCount + badCount);
  
  if (ratio >= 0.8) return getRandomFromArray(LIFE_SUMMARIES.EXCELLENT);
  if (ratio >= 0.6) return getRandomFromArray(LIFE_SUMMARIES.GOOD);
  if (ratio >= 0.4) return getRandomFromArray(LIFE_SUMMARIES.AVERAGE);
  if (ratio >= 0.2) return getRandomFromArray(LIFE_SUMMARIES.BAD);
  return getRandomFromArray(LIFE_SUMMARIES.TERRIBLE);
};

// 生成异世界人生经历
const generateFantasyLifeStory = (ctx) => {
  const playerName = ctx.player?.name || '冒险者';
  
  // 随机选择种族
  const selectedRace = getRandomFromArray(RACES);
  
  // 使用随机开场文案
  let lifeStory = getRandomStartText(playerName);
  lifeStory += `🎭 转生种族：${selectedRace.name}\n`;
  lifeStory += `   ${selectedRace.desc}\n`;
  lifeStory += `   种族特质：${selectedRace.traits.join('，')}\n\n`;
  lifeStory += `✨ 开始生成你的异世界人生...\n\n`;
  
  const stages = Object.keys(CONFIG.LIFE_STAGES);
  const lifeEvents = {
    RACE: { 
      title: selectedRace.name, 
      desc: selectedRace.desc,
      isGood: true 
    }
  };
  
  // 为每个阶段生成事件（除了种族）
  stages.filter(stage => stage !== 'RACE').forEach(stage => {
    const stageName = CONFIG.LIFE_STAGES[stage];
    const eventPool = LIFE_EVENTS[stage];
    const [eventTitle, eventDesc, isGood] = getRandomFromArray(eventPool);
    
    // 在描述中替换种族占位符
    const finalDesc = eventDesc.replace('{race}', selectedRace.name);
    
    lifeEvents[stage] = { 
      title: eventTitle, 
      desc: finalDesc, 
      isGood: isGood 
    };
    
    const emoji = isGood ? "✨" : "💔";
    lifeStory += `${emoji} ${stageName}：\n`;
    lifeStory += `   ${eventTitle} - ${finalDesc}\n\n`;
  });
  
  // 生成人生总结
  const summary = calculateLifeSummary(lifeEvents);
  lifeStory += CONFIG.LIFE_END_TEXT.replace('{summary}', summary);
  
  return lifeStory;
};

